async page => {
 const url='http://127.0.0.1:8766/';
 const check=(value,message)=>{if(!value) throw Error(message)};
 await page.emulateMedia({reducedMotion:'no-preference'});
 await page.setViewportSize({width:1440,height:950});
 await page.goto(url);
 const scene=page.locator('#heroScene');
 await scene.locator('[data-view=pixel]').click();
 await scene.locator('[data-view=real]').click();
 check(await scene.locator('.scene-portrait-real').isVisible(),'Real photo not visible');
 check(await scene.locator('.scene-fragment').count() > 0,'Pixel transition missing');
 await page.waitForFunction(()=>!document.querySelector('.scene-fragment'));
 await page.screenshot({path:'refined-real-1440.jpg',animations:'disabled',quality:85});
 await scene.locator('[data-view=proof]').click();
 check(await scene.locator('.scene-proof').getAttribute('aria-hidden') === 'false','Proof inactive');
 await scene.locator('[data-view=pixel]').click();
 await page.locator('#languageSwitch').click();
 await page.evaluate(async()=>{await document.fonts.ready;scrollTo({top:0,behavior:'instant'})});
 await page.screenshot({path:'refined-hero-1440.jpg',animations:'disabled',quality:88});
 await page.evaluate(()=>document.getElementById('work').scrollIntoView({behavior:'instant'}));
 await page.waitForFunction(()=>document.querySelector('.desktop-nav a[aria-current]').hash === '#work');
 await page.screenshot({path:'refined-work-1440.jpg',animations:'disabled',quality:88});
 const opener = page.locator('[data-project=numoo].feature-link');
 await opener.click();
 await page.context().grantPermissions(['clipboard-read','clipboard-write'], {origin:url});
 await page.locator('#caseCopy').click();
 await page.waitForFunction(()=>document.getElementById('caseShareStatus').textContent.includes('copied'));
 check((await page.evaluate(()=>navigator.clipboard.readText())).endsWith('?case=numoo'),'Clipboard case URL wrong');
 await page.locator('#modalLinks a[href$="#lab-integrate"]').click();
 check(await page.locator('#projectDialog').isHidden(),'Case dialog left open');
 check(await page.locator('#proofLab').getAttribute('data-lab') === 'integrate','Wrong lab selected');
 check(await page.evaluate(()=>location.hash === '#lab-integrate' && document.activeElement.id === 'lab-integrate'),'Lab focus or hash');
 await page.goto(url + '?case=numoo');
 await page.locator('#modalLinks a[href$="#lab-integrate"]').click();
 check(new URL(page.url()).searchParams.get('case') === null,'Case parameter leaked into lab');
 await page.reload();
 check(await page.locator('#projectDialog').isHidden(),'Reload reopened the case');
 check(await page.locator('#proofLab').getAttribute('data-lab') === 'integrate','Reload lost the lab mode');
 await page.goBack();
 check(await page.locator('#projectDialog').isVisible(),'Back did not restore the linked case');
 await page.keyboard.press('Escape');
 await page.waitForFunction(()=>!new URLSearchParams(location.search).has('case'));
 await page.setViewportSize({width:390,height:844});
 await page.goto(url);
 await page.locator('#languageSwitch').click();
 await page.locator('#themeToggle').click();
 await page.evaluate(async()=>{await document.fonts.ready;scrollTo({top:0,behavior:'instant'})});
 await page.screenshot({path:'refined-hero-390.jpg',animations:'disabled',quality:85});
 await page.evaluate(()=>document.getElementById('work').scrollIntoView({behavior:'instant'}));
 await page.screenshot({path:'refined-work-390.jpg',animations:'disabled',quality:85});
 await page.locator('[data-project=ncm].feature-link').click();
 await page.locator('#modalLinks a[href$="#lab-observe"]').click();
 check(await page.locator('#proofLab').getAttribute('data-lab') === 'observe','Wrong NCM lab selected');
 await page.setViewportSize({width:1440,height:920});
 await page.evaluate(()=>scrollTo({top:document.documentElement.scrollHeight,behavior:'instant'}));
 await page.waitForFunction(()=>document.querySelector('.desktop-nav a[aria-current]').hash === '#contact');
 return {sceneStates:'passed',pixelLifecycle:'passed',caseShare:'passed',caseToLab:'passed',scrollNavigation:'passed'};
}
